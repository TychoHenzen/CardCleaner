namespace CardCleaner.Scripts.Features.Worldgen.IrregularMesh;

/// <summary>
/// The irregular map's screen: a view of <see cref="IGameSessionService"/>, like the grid screen. It starts a session
/// with <see cref="Initialize"/> and then draws what that session reports: the map once generated, every move as a
/// smooth step from cell to cell, the fog, defeated enemies and the loot. It acts only on a session it started, from
/// its start call until the session falls back to waiting or the screen is reset.
/// Renders 2D content via SubViewport onto a 3D mesh for world-space display.
/// </summary>
public partial class IrregularWorldMapScreen : Node3D, ISessionView, IDependent
{
    [Export] public bool ShowDebug { get; set; }
    [Export] public bool FogOfWarEnabled { get; set; } = true;
    [Export] public bool UseRaycastVisibility { get; set; }
    [Export] public SubViewport? Viewport { get; set; }
    [Export] public MeshInstance3D? ScreenMesh { get; set; }
    [Export] public Label? StatusLabel { get; set; }
    [Export] public Node3D? LootSpawnPoint { get; set; }

    private const float LootCardSpacing = 0.5f;

    private IrregularMeshDebugRenderer? _debugRenderer;
    private Camera2D? _camera2D;

    // Tile registry the render layer reads tile art from
    private ITileRegistry? _tileRegistry;

    private IServiceResolver? _services;

    // The screen acts only on a session it started: the link passes events on while the screen owns the session.
    private readonly SessionViewLink _link;
    private readonly IrregularMapPresenter _presenter;

    public IIrregularMesh? Mesh => _presenter.Mesh;
    public IMapData? MapData => _presenter.MapData;
    public IrregularMeshFogOfWar? FogOfWar => _presenter.FogOfWar;
    public bool IsInitialized => _presenter.HasView;

    public event Action? MapGenerated;
    public event Action<int, Vector2>? PlayerMoved;
    public event Action<int>? EnemyDefeated;

    public IrregularWorldMapScreen()
    {
        _link = new SessionViewLink(this);
        _presenter = new IrregularMapPresenter(_link, OnStepShown);
    }

    public void Inject(IServiceResolver services) => _services = services;

    // The first entry connects in _Ready, because the root injects after _EnterTree. A re-entry still holds the
    // resolver from the first injection and reconnects here: _ExitTree disconnected, and _Ready does not run again.
    public override void _EnterTree()
    {
        if (_services != null && !_link.IsConnected)
            _services.Get<IGameSessionService>(_link.Connect);
    }

    public override void _Ready()
    {
        ResolveServices();

        CallDeferred(nameof(SetupScreenMesh));
        CallDeferred(nameof(SetupScreenMaterial));

        CreateChildNodes();
    }

    // A separate method so the mesh setup and child nodes in _Ready still come when not injected.
    private void ResolveServices()
    {
        if (_services == null)
        {
            ILog.Error($"{Name} was not injected");
            return;
        }

        _services.Get<ITileRegistry>(registry => { _tileRegistry = registry; });
        if (!_link.IsConnected)
            _services.Get<IGameSessionService>(_link.Connect);
    }

    public override void _ExitTree()
    {
        _link.Disconnect();
    }

    /// <summary>
    /// Starts a session for the seed cards on the session service, generated by <paramref name="generator"/>; the
    /// screen then shows that session. Before the service resolves, the start waits for it.
    /// </summary>
    public void Initialize(CardSignature[] mapSeed, CardSignature[] abilities, IMapGenerator generator)
    {
        ArgumentNullException.ThrowIfNull(generator);
        if (mapSeed.Length == 0)
        {
            ILog.Error("Initialize called with empty mapSeed array");
            return;
        }

        _link.Start(mapSeed, abilities, generator);
    }

    public void ToggleDebug()
    {
        ShowDebug = !ShowDebug;
        if (_debugRenderer != null) _debugRenderer.Visible = ShowDebug;
    }

    public void RevealAll() => _presenter.RevealAll();

    /// <summary>
    /// Names the picked map kind in this screen's status label. The session's status text replaces it while a
    /// session runs; the cabinet shows the kind again after the reset press.
    /// </summary>
    public void ShowMapKind(string kindText) => ShowStatus(kindText);

    /// <summary>
    /// Clears the map and lets go of the session; the cabinet calls it with the reset press after a session ends.
    /// </summary>
    public void Reset()
    {
        _link.Reset();
        _presenter.CloseView();
    }

    // A session service that resolves after the screen left the tree or was freed must not subscribe it.
    bool ISessionView.CanConnect => IsInstanceValid(this) && IsInsideTree();

    /// <summary>
    /// Clears the last session's map before the link starts a new session, and hands over the raycast checker when
    /// the screen sees with raycasts.
    /// </summary>
    IVisibilityChecker? ISessionView.PrepareForSession()
    {
        _presenter.CloseView();
        return CreateVisibilityChecker();
    }

    // ASSUMPTION: the raycast checker reads the viewport's 2D space, whose opaque terrain shapes the render layer
    // builds when the map arrives; exploration first asks it after that, once the session starts exploring.
    private IVisibilityChecker? CreateVisibilityChecker() =>
        UseRaycastVisibility && Viewport != null
            ? new RaycastVisibilityChecker(Viewport.World2D.DirectSpaceState)
            : null;

    void ISessionView.OnStateChanged(SessionState state)
    {
        if (StatusText(state) is { } text)
            ShowStatus(text);
        if (state == SessionState.GeneratingLoot)
            RevealAll();
    }

    private static string? StatusText(SessionState state) => state switch
    {
        SessionState.GeneratingMap => "Generating map...",
        SessionState.Exploring => "Exploring map...",
        SessionState.InCombat => "Combat started!",
        SessionState.GeneratingLoot => "Generating loot...",
        SessionState.SessionComplete => "Session complete!",
        _ => null
    };

    void ISessionView.OnSessionReleased() => _presenter.ReleaseSession();

    /// <summary>
    /// Shows the map of a session this screen started. The session's generator must give an irregular mesh map: the
    /// screen checks that here, once, and any other map throws, which ends the session.
    /// </summary>
    void ISessionView.OnMapReady(IGeneratedMap generated)
    {
        if (generated is not IMeshGeneratedMap meshMap)
            throw new InvalidOperationException("The session's generator returned no irregular mesh map");

        _presenter.ShowMap(meshMap, CreateSettings(meshMap.WorldScale));
        MapGenerated?.Invoke();
    }

    void ISessionView.OnPlayerMoved(Vector2 worldPos) => _presenter.OnPlayerMoved(worldPos);

    private void OnStepShown(int cellId, Vector2 worldPos)
    {
        PlayerMoved?.Invoke(cellId, worldPos);
        ShowStatus($"Cell: {cellId} Pos: {worldPos:F1}");
    }

    void ISessionView.OnVisibilityUpdated(IReadOnlySet<int> seenCells, IReadOnlySet<int> visibleCells) =>
        _presenter.OnVisibilityUpdated(seenCells, visibleCells);

    void ISessionView.OnEnemyDefeated(int cellId)
    {
        _presenter.OnEnemyDefeated(cellId);
        EnemyDefeated?.Invoke(cellId);
    }

    void ISessionView.OnLootGenerated(List<CardSignature> lootSignatures)
    {
        ILog.Print($"Loot generated: {lootSignatures.Count} cards");
        if (NodeExports.ExportCheck(LootSpawnPoint, nameof(LootSpawnPoint), this))
            return;

        SpawnLootRow(lootSignatures, LootSpawnPoint!.GlobalTransform);
    }

    // Lays the loot cards out in a row that starts at the loot point and runs along that point's X axis.
    private void SpawnLootRow(List<CardSignature> lootSignatures, Transform3D lootPoint)
    {
        if (_services == null)
        {
            ILog.Error($"{Name} was not injected, so it cannot spawn loot");
            return;
        }

        var rowDirection = lootPoint.Basis.Orthonormalized().X;
        var services = _services;

        services.Get<ICardSpawningService>(spawningService =>
            services.Get<ICardSpawner>(spawner =>
            {
                for (var i = 0; i < lootSignatures.Count; i++)
                {
                    var spawnTransform = Transform3D.Identity;
                    spawnTransform.Origin = lootPoint.Origin + rowDirection * (i * LootCardSpacing);
                    spawningService.SpawnCard(lootSignatures[i], spawnTransform, spawner.GetNode());
                }

                ILog.Print($"Spawned {lootSignatures.Count} loot cards!");
            }));
    }

    // The irregular view draws no path.
    void ISessionView.OnPathUpdated(IReadOnlyList<int> pathCells, int? targetCell)
    {
    }

    private WorldMapSettings CreateSettings(float worldScale)
    {
        return new WorldMapSettings
        {
            WorldScale = worldScale,
            FogOfWarEnabled = FogOfWarEnabled,
            UseRaycastVisibility = UseRaycastVisibility,
            Viewport = Viewport,
            Camera = _camera2D,
            DebugRenderer = _debugRenderer,
            TileRegistry = _tileRegistry
        };
    }

    private void CreateChildNodes()
    {
        if (Viewport == null)
        {
            GD.PrintErr("[IrregularWorldMapScreen] Viewport not assigned!");
            return;
        }

        _camera2D = IrregularScreenNodes.FindOrCreateCamera(Viewport);
        _debugRenderer = IrregularScreenNodes.CreateDebugRenderer(Viewport, ShowDebug);
        _presenter.PlayerSprite = IrregularScreenNodes.CreatePlayerSprite(Viewport);
    }

    private void SetupScreenMesh()
    {
        if (ScreenMesh == null) return;
        ViewportScreenSetup.SetupScreenMesh(ScreenMesh);
    }

    private void SetupScreenMaterial()
    {
        if (Viewport == null || ScreenMesh == null) return;
        ViewportScreenSetup.SetupScreenMaterial(Viewport, ScreenMesh);
    }

    private void ShowStatus(string text)
    {
        if (StatusLabel != null) StatusLabel.Text = text;
    }
}
